// import = bring in code from another file or package
// NavLink = a Link that knows if it's the current page (isActive) for highlighting
// Outlet = where the child route's page appears inside a layout
import { NavLink, Outlet } from 'react-router';
// import = bring in code from another file or package
import { ExternalLink, FileText, LayoutDashboard, LogOut, Package, ShieldCheck, ShoppingBag, Users } from 'lucide-react';
// import = bring in code from another file or package
// useAppSelector = our useSelector (app/hooks.js)
import { useAppSelector } from '@/app/hooks';
// import = bring in code from another file or package
// useLogoutMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
import { useLogoutMutation } from '@/features/auth/authApi';
// import = bring in code from another file or package
import { STORE_URL } from '@/lib/config';

// const = a name for a value that is never reassigned
const nav = [
  { to: '/', label: 'Dashboard', icon: LayoutDashboard, end: true },
  { to: '/products', label: 'Products', icon: Package },
  { to: '/orders', label: 'Orders', icon: ShoppingBag },
  { to: '/customers', label: 'Customers', icon: Users },
  { to: '/content', label: 'Content', icon: FileText },
];

// Sidebar + top bar around every admin page. <Outlet /> is where the current page renders.
// export = other files can import this
// function Name() = a React component (capital letter): returns what to show (JSX)
export function AdminLayout() {
  // const = a name for a value that is never reassigned
  // useAppSelector = our useSelector (app/hooks.js)
  // => = an arrow function (a short function)
  const user = useAppSelector((s) => s.auth.user);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useLogoutMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [logout] = useLogoutMutation();

  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="flex min-h-screen">
      {/* <aside> = side content next to the main content
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <aside className="sticky top-0 flex h-screen w-60 shrink-0 flex-col bg-slate-900 text-slate-300">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <div className="flex items-center gap-2 px-5 py-5 text-white">
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <ShieldCheck className="size-6 text-brand-500" />
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <span className="font-bold">ShopVerse Admin</span>
        </div>
        {/* <nav> = a navigation area (screen readers can jump to it)
           className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <nav className="flex-1 space-y-1 px-3">
          {/* { } in JSX = run JavaScript here and show its result
             .map = make a new array by transforming each item (in JSX: one element per item)
             => = an arrow function (a short function)
             { a, b } = destructuring: take properties a and b out of an object */}
          {nav.map(({ to, label, icon: Icon, end }) => (
            // NavLink = a Link that knows if it's the current page (isActive) for highlighting
            <NavLink
              // key = a stable id for list items so React can track them between redraws
              // { } in JSX = run JavaScript here and show its result
              key={to}
              // { } in JSX = run JavaScript here and show its result
              to={to}
              // { } in JSX = run JavaScript here and show its result
              end={end}
              // className = CSS classes (Tailwind) for this element (class is a JS keyword)
              // { } in JSX = run JavaScript here and show its result
              // => = an arrow function (a short function)
              // { a, b } = destructuring: take properties a and b out of an object
              className={({ isActive }) =>
                // `text ${x}` = a template string: text with values inserted
                // a ? b : c = ternary: if a then b else c
                `flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium ${isActive ? 'bg-slate-800 text-white' : 'hover:bg-slate-800/60 hover:text-white'}`
              }
            >
              {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                 { } in JSX = run JavaScript here and show its result */}
              <Icon className="size-4" /> {label}
            </NavLink>
          ))}
        </nav>
        <a
          // { } in JSX = run JavaScript here and show its result
          href={STORE_URL}
          target="_blank"
          rel="noreferrer"
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="mx-3 mb-4 flex items-center gap-2 rounded-lg px-3 py-2 text-sm hover:bg-slate-800/60 hover:text-white"
        >
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <ExternalLink className="size-4" /> View store
        </a>
      </aside>

      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="flex min-w-0 flex-1 flex-col">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <header className="flex h-14 items-center justify-end gap-3 border-b border-slate-200 bg-white px-6">
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <span className="text-sm text-slate-600">
            {/* { } in JSX = run JavaScript here and show its result
               ?. = optional chaining: stop (undefined) instead of crashing if the left side is null/undefined */}
            {user?.name} · {user?.email}
          </span>
          <button
            // onClick = what happens on click/tap
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onClick={() => logout()}
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="rounded-lg p-2 text-slate-600 hover:bg-slate-100"
            title="Log out"
            // aria-label = the name screen readers read for this element
            aria-label="Log out"
          >
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <LogOut className="size-4" />
          </button>
        </header>
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <main className="flex-1 p-6">
          {/* Outlet = where the child route's page appears inside a layout */}
          <Outlet />
        </main>
      </div>
    </div>
  );
}
