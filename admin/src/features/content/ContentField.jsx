// const = a name for a value that is never reassigned
const MAX_FILE_MB = 10;

// Upload in two steps, without the file ever passing through our servers:
//   1. ask the CMS for a signed permission (POST /cms/admin/uploads/banner-signature)
//   2. send the file straight to Cloudinary with it; Cloudinary answers with the image URL
// The URL is saved when the admin clicks Save (the CMS checks it's one of OUR banner images).
// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
// onChange = runs on every change of an input
function ImageField({ field, value, error, onChange }) {
  // const = a name for a value that is never reassigned
  // useRef = a box (.current) that keeps a value or a DOM element without causing a redraw
  const inputRef = useRef(null);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useSignBannerUploadMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [signUpload] = useSignBannerUploadMutation();
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [uploading, setUploading] = useState(false);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [uploadError, setUploadError] = useState(null);

  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  // async = this function works with await and returns a Promise
  const upload = async (file) => {
    setUploadError(null);
    // if (...) = run the next part only when the condition is true
    // ! = NOT: flips true/false
    // .includes = true if the array/string contains the value
    if (!['image/jpeg', 'image/png', 'image/webp'].includes(file.type)) {
      // return = give this value back and stop the function here
      return setUploadError('Choose a JPG, PNG or WebP image');
    }
    // if (...) = run the next part only when the condition is true
    // return = give this value back and stop the function here
    // `text ${x}` = a template string: text with values inserted
    if (file.size > MAX_FILE_MB * 1024 * 1024) return setUploadError(`The image must be under ${MAX_FILE_MB} MB`);

    setUploading(true);
    // try / catch = if the code inside fails, run the catch part instead of crashing
    try {
      // const = a name for a value that is never reassigned
      // await = wait for a Promise (async result) before continuing
      // .unwrap() = turn the mutation result into a normal Promise: returns data or throws the error
      const signed = await signUpload().unwrap();
      // const = a name for a value that is never reassigned
      // new = create an object from a class (e.g. new Date())
      // FormData = form fields + files to send in one request (used for uploads)
      const form = new FormData();
      // Object.entries = [key, value] pairs of an object
      // => = an arrow function (a short function)
      // [a, b] = destructuring: take the first and second items of an array
      Object.entries(signed.fields).forEach(([key, val]) => form.append(key, String(val)));
      form.append('file', file);
      // const = a name for a value that is never reassigned
      // await = wait for a Promise (async result) before continuing
      // fetch = the browser's built-in way to send an HTTP request
      const res = await fetch(signed.uploadUrl, { method: 'POST', body: form });
      // const = a name for a value that is never reassigned
      // await = wait for a Promise (async result) before continuing
      const body = await res.json();
      // if (...) = run the next part only when the condition is true
      // ! = NOT: flips true/false
      // throw = stop here with an error
      // new = create an object from a class (e.g. new Date())
      // ?. = optional chaining: stop (undefined) instead of crashing if the left side is null/undefined
      // a ?? b = a, unless a is null/undefined, then b
      if (!res.ok) throw new Error(body.error?.message ?? 'Upload failed');
      // onChange = runs on every change of an input
      onChange(body.secure_url);
    } catch (err) {
      // a ? b : c = ternary: if a then b else c
      setUploadError(err instanceof Error ? err.message : getErrorMessage(err));
    } finally {
      setUploading(false);
    }
  };

  // const = a name for a value that is never reassigned
  // a ?? b = a, unless a is null/undefined, then b
  const message = uploadError ?? error;
  // return = give this value back and stop the function here
  return (
    <div>
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
         { } in JSX = run JavaScript here and show its result */}
      <span className="mb-1.5 block text-sm font-medium text-slate-700">{field.label}</span>
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="flex flex-wrap items-center gap-4">
        <div
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          // { } in JSX = run JavaScript here and show its result
          // `text ${x}` = a template string: text with values inserted
          // a ? b : c = ternary: if a then b else c
          className={`flex aspect-[12/5] w-48 shrink-0 items-center justify-center overflow-hidden rounded-lg border bg-slate-50 ${message ? 'border-red-400' : 'border-slate-200'}`}
        >
          {/* { } in JSX = run JavaScript here and show its result
             a ? b : c = ternary: if a then b else c */}
          {value ? (
            // { } in JSX = run JavaScript here and show its result
            // alt = text describing the image for screen readers (empty = decorative)
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            <img src={resized(value, 'c_fill,w_400,h_167,q_auto,f_auto')} alt="" className="size-full object-cover" />
          ) : (
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            // aria-hidden = screen readers skip this (decoration)
            <ImagePlus className="size-6 text-slate-400" aria-hidden />
          )}
        </div>
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <div className="space-y-1">
          {/* onClick = what happens on click/tap
             { } in JSX = run JavaScript here and show its result
             => = an arrow function (a short function)
             ?.() = call only if the function exists
             ?. = optional chaining: stop (undefined) instead of crashing if the left side is null/undefined
             disabled = can't be clicked or typed in */}
          <Button type="button" variant="secondary" onClick={() => inputRef.current?.click()} disabled={uploading}>
            {/* { } in JSX = run JavaScript here and show its result
               a ? b : c = ternary: if a then b else c
               className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            {uploading ? <Loader2 className="size-4 animate-spin" /> : <ImagePlus className="size-4" />}
            {/* { } in JSX = run JavaScript here and show its result
               a ? b : c = ternary: if a then b else c */}
            {uploading ? 'Uploading...' : value ? 'Replace image' : 'Upload image'}
          </Button>
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
             { } in JSX = run JavaScript here and show its result */}
          <p className="text-xs text-slate-500">JPG, PNG or WebP, up to {MAX_FILE_MB} MB.</p>
        </div>
        <input
          // ref = after drawing, put this element into a useRef box (.current)
          // { } in JSX = run JavaScript here and show its result
          ref={inputRef}
          type="file"
          // accept = which file types the file picker shows
          accept="image/jpeg,image/png,image/webp"
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="hidden"
          // onChange = runs on every change of an input
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          onChange={(e) => {
            // const = a name for a value that is never reassigned
            // ?. = optional chaining: stop (undefined) instead of crashing if the left side is null/undefined
            const file = e.target.files?.[0];
            e.target.value = ''; // so choosing the same file again still triggers a change
            // if (...) = run the next part only when the condition is true
            if (file) upload(file);
          }}
        />
      </div>
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      {message && <p className="mt-1 text-xs text-red-600">{message}</p>}
    </div>
  );
}

