// import = bring in code from another file or package
import { cmsApi } from '@/app/api';

// Store text, from the CMS (cms/), not the shop API.
// export = other files can import this
// const = a name for a value that is never reassigned
// injectEndpoints = add endpoints to the shared API from a feature file
export const contentApi = cmsApi.injectEndpoints({
  // endpoints = the list of requests this API can make
  // => = an arrow function (a short function)
  endpoints: (build) => ({
    // Every content type with its field descriptions and current values: what the editor draws.
    // build.query = define a READ request: cached, and turned into a useXxxQuery hook
    getEditorContent: build.query({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      query: () => '/admin/content',
      // transformResponse = reshape the server answer before it is cached
      // => = an arrow function (a short function)
      transformResponse: (res) => res.types,
      // providesTags = label this cached data (e.g. Order 5) so it can be refreshed later
      providesTags: ['Content'],
    }),
    // Saves ALL fields of one type at once (the CMS validates them together).
    // build.mutation = define a CHANGE request (POST/PATCH/DELETE): turned into a useXxxMutation hook
    saveContent: build.mutation({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      // { a, b } = destructuring: take properties a and b out of an object
      // `text ${x}` = a template string: text with values inserted
      query: ({ type, values }) => ({ url: `/admin/content/${type}`, method: 'PUT', body: values }),
      // invalidatesTags = after this change, refetch every query with these labels
      invalidatesTags: ['Content'], // refetch, so "last saved" and every form show what's really stored
    }),
    // Permission to upload ONE banner image straight to Cloudinary (see ImageField)
    // build.mutation = define a CHANGE request (POST/PATCH/DELETE): turned into a useXxxMutation hook
    signBannerUpload: build.mutation({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      query: () => ({ url: '/admin/uploads/banner-signature', method: 'POST' }),
    }),
  }),
});

// export = other files can import this
// const = a name for a value that is never reassigned
// { a, b } = destructuring: take properties a and b out of an object
// useGetEditorContentQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
// useSaveContentMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
// useSignBannerUploadMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
export const { useGetEditorContentQuery, useSaveContentMutation, useSignBannerUploadMutation } = contentApi;
