// import = bring in code from another file or package
// useState = a value the component remembers; calling its setter redraws the component
import { useState } from 'react';
// import = bring in code from another file or package
// Navigate = redirect to another URL as soon as it is drawn
// useLocation = the current URL (pathname, search) and any state passed to it
// useNavigate = gives navigate(url) to change page from code
import { Navigate, useLocation, useNavigate } from 'react-router';
// import = bring in code from another file or package
import { ShieldCheck } from 'lucide-react';
// import = bring in code from another file or package
import { Button } from '@/components/ui/Button';
// import = bring in code from another file or package
import { Input } from '@/components/ui/Input';
// import = bring in code from another file or package
import { ErrorState } from '@/components/ui/States';
// import = bring in code from another file or package
// useAppSelector = our useSelector (app/hooks.js)
import { useAppSelector } from '@/app/hooks';
// import = bring in code from another file or package
import { getErrorMessage } from '@/lib/format';
// import = bring in code from another file or package
// useLoginMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
import { useLoginMutation } from './authApi';

// export = other files can import this
// function Name() = a React component (capital letter): returns what to show (JSX)
export function LoginPage() {
  // const = a name for a value that is never reassigned
  // useNavigate = gives navigate(url) to change page from code
  const navigate = useNavigate();
  // const = a name for a value that is never reassigned
  // useLocation = the current URL (pathname, search) and any state passed to it
  const location = useLocation();
  // const = a name for a value that is never reassigned
  // ?. = optional chaining: stop (undefined) instead of crashing if the left side is null/undefined
  // a ?? b = a, unless a is null/undefined, then b
  const from = location.state?.from ?? '/';
  // const = a name for a value that is never reassigned
  // useAppSelector = our useSelector (app/hooks.js)
  // => = an arrow function (a short function)
  const status = useAppSelector((s) => s.auth.status);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // { a, b } = destructuring: take properties a and b out of an object
  // isLoading = first load, no data yet
  // useLoginMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [login, { isLoading, error }] = useLoginMutation();
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [form, setForm] = useState({ email: '', password: '' });
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [notAdmin, setNotAdmin] = useState(false);

  // if (...) = run the next part only when the condition is true
  // === = strictly equal (same value AND same type)
  // return = give this value back and stop the function here
  // Navigate = redirect to another URL as soon as it is drawn
  // { } in JSX = run JavaScript here and show its result
  if (status === 'authenticated') return <Navigate to={from} replace />;

  // const = a name for a value that is never reassigned
  // onSubmit = runs when the form is sent (Enter or submit button)
  // => = an arrow function (a short function)
  // async = this function works with await and returns a Promise
  const onSubmit = async (e) => {
    // preventDefault = stop the browser's default action (form submit reload, link follow)
    e.preventDefault();
    setNotAdmin(false);
    // try / catch = if the code inside fails, run the catch part instead of crashing
    try {
      // unwrap(): gives the response data, or throws the error, like a normal async function.
      // const = a name for a value that is never reassigned
      // await = wait for a Promise (async result) before continuing
      // .unwrap() = turn the mutation result into a normal Promise: returns data or throws the error
      const data = await login(form).unwrap();
      // if (...) = run the next part only when the condition is true
      // !== = not strictly equal
      if (data.user.role !== 'ADMIN') setNotAdmin(true);
      else navigate(from, { replace: true });
    } catch {
      // the error is shown from `error` below
    }
  };

  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="flex min-h-screen items-center justify-center p-4">
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="w-full max-w-sm rounded-2xl border border-slate-200 bg-white p-8 shadow-sm">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <div className="mb-6 flex items-center gap-2">
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <ShieldCheck className="size-7 text-brand-600" />
          <div>
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <h1 className="text-xl font-bold">ShopVerse Admin</h1>
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <p className="text-sm text-slate-500">Staff only</p>
          </div>
        </div>

        {/* <form> = groups inputs; Enter or a submit button sends it (onSubmit)
           onSubmit = runs when the form is sent (Enter or submit button)
           { } in JSX = run JavaScript here and show its result
           className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <form onSubmit={onSubmit} className="space-y-4">
          {/* { } in JSX = run JavaScript here and show its result
             a && b = AND; in JSX: show b only when a is true */}
          {error && <ErrorState message={getErrorMessage(error)} />}
          {/* { } in JSX = run JavaScript here and show its result
             a && b = AND; in JSX: show b only when a is true */}
          {notAdmin && <ErrorState message="This account is not an admin. Use the store to shop." />}
          <Input
            label="Email"
            name="email"
            type="email"
            // required = the browser won't submit the form while this is empty
            required
            // autoComplete = tells the browser what to auto-fill (email, password, address...)
            autoComplete="username"
            // { } in JSX = run JavaScript here and show its result
            value={form.email}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            // ...x = spread: copy all items/properties of x into here
            onChange={(e) => setForm({ ...form, email: e.target.value })}
          />
          <Input
            label="Password"
            name="password"
            type="password"
            // required = the browser won't submit the form while this is empty
            required
            // autoComplete = tells the browser what to auto-fill (email, password, address...)
            autoComplete="current-password"
            // { } in JSX = run JavaScript here and show its result
            value={form.password}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            // ...x = spread: copy all items/properties of x into here
            onChange={(e) => setForm({ ...form, password: e.target.value })}
          />
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
             loading="lazy" = load the image only when it gets near the screen
             { } in JSX = run JavaScript here and show its result
             isLoading = first load, no data yet */}
          <Button type="submit" className="w-full py-2.5" loading={isLoading}>
            Log in
          </Button>
        </form>

        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <div className="mt-4 rounded-lg bg-brand-50 p-3 text-xs text-brand-700">
          Demo admin: <b>admin@shopverse.dev</b> / <b>Admin@12345</b>
          <button
            type="button"
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="ml-2 underline"
            // onClick = what happens on click/tap
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onClick={() => setForm({ email: 'admin@shopverse.dev', password: 'Admin@12345' })}
          >
            Fill in
          </button>
        </div>
      </div>
    </div>
  );
}
