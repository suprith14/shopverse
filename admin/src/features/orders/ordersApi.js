// import = bring in code from another file or package
import { api } from '@/app/api';

// const = a name for a value that is never reassigned
const LIST = { type: 'Order', id: 'LIST' };

// export = other files can import this
// const = a name for a value that is never reassigned
// injectEndpoints = add endpoints to the shared API from a feature file
export const ordersApi = api.injectEndpoints({
  // endpoints = the list of requests this API can make
  // => = an arrow function (a short function)
  endpoints: (build) => ({
    // build.query = define a READ request: cached, and turned into a useXxxQuery hook
    getOrders: build.query({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      query: (params) => ({ url: '/admin/orders', params }),
      // providesTags = label this cached data (e.g. Order 5) so it can be refreshed later
      // => = an arrow function (a short function)
      // ...x = spread: copy all items/properties of x into here
      // ?.() = call only if the function exists
      // ?. = optional chaining: stop (undefined) instead of crashing if the left side is null/undefined
      // .map = make a new array by transforming each item (in JSX: one element per item)
      // a ?? b = a, unless a is null/undefined, then b
      providesTags: (result) => [LIST, ...(result?.items.map((o) => ({ type: 'Order', id: o.id })) ?? [])],
    }),
    // build.query = define a READ request: cached, and turned into a useXxxQuery hook
    getOrder: build.query({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      // `text ${x}` = a template string: text with values inserted
      query: (id) => `/admin/orders/${id}`,
      // transformResponse = reshape the server answer before it is cached
      // => = an arrow function (a short function)
      transformResponse: (res) => res.order,
      // providesTags = label this cached data (e.g. Order 5) so it can be refreshed later
      // => = an arrow function (a short function)
      providesTags: (_r, _e, id) => [{ type: 'Order', id }],
    }),
    // Order changes also change dashboard numbers (status counts, revenue after refunds).
    // build.mutation = define a CHANGE request (POST/PATCH/DELETE): turned into a useXxxMutation hook
    updateOrderStatus: build.mutation({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      // { a, b } = destructuring: take properties a and b out of an object
      // `text ${x}` = a template string: text with values inserted
      query: ({ id, status }) => ({ url: `/admin/orders/${id}/status`, method: 'PATCH', body: { status } }),
      // transformResponse = reshape the server answer before it is cached
      // => = an arrow function (a short function)
      transformResponse: (res) => res.order,
      // invalidatesTags = after this change, refetch every query with these labels
      // => = an arrow function (a short function)
      // { a, b } = destructuring: take properties a and b out of an object
      invalidatesTags: (_r, _e, { id }) => [LIST, { type: 'Order', id }, 'Analytics'],
    }),
    // A refund with restock puts units back, so product stock is affected too.
    // build.mutation = define a CHANGE request (POST/PATCH/DELETE): turned into a useXxxMutation hook
    refundOrder: build.mutation({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      // { a, b } = destructuring: take properties a and b out of an object
      // `text ${x}` = a template string: text with values inserted
      query: ({ id, restock }) => ({ url: `/admin/orders/${id}/refund`, method: 'POST', body: { restock } }),
      // transformResponse = reshape the server answer before it is cached
      // => = an arrow function (a short function)
      transformResponse: (res) => res.order,
      // invalidatesTags = after this change, refetch every query with these labels
      // => = an arrow function (a short function)
      // { a, b } = destructuring: take properties a and b out of an object
      invalidatesTags: (_r, _e, { id }) => [LIST, { type: 'Order', id }, 'Analytics', { type: 'Product', id: 'LIST' }],
    }),
  }),
});

// export = other files can import this
// const = a name for a value that is never reassigned
// { a, b } = destructuring: take properties a and b out of an object
// useGetOrdersQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
// useGetOrderQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
// useUpdateOrderStatusMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
// useRefundOrderMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
export const { useGetOrdersQuery, useGetOrderQuery, useUpdateOrderStatusMutation, useRefundOrderMutation } = ordersApi;
