import { useGetOrdersByStatusQuery } from '@/features/analytics/analyticsApi';
// import = bring in code from another file or package
// useGetOrdersQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
import { useGetOrdersQuery } from './ordersApi';
// import = bring in code from another file or package
import { statusStyles, statusTabs } from './orderStatus';
// import = bring in code from another file or package
import { OrderStatusBadge } from './OrderStatusBadge';

// export = other files can import this
// function Name() = a React component (capital letter): returns what to show (JSX)
export function OrdersPage() {
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useSearchParams = read/write the ?query=part of the URL
  const [params, setParams] = useSearchParams();
  // const = a name for a value that is never reassigned
  const filters = {
    // a ?? b = a, unless a is null/undefined, then b
    status: params.get('status') ?? undefined,
    // a ?? b = a, unless a is null/undefined, then b
    q: params.get('q') ?? undefined,
    // a ?? b = a, unless a is null/undefined, then b
    page: Number(params.get('page') ?? 1),
  };

  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  const setFilter = (patch) => {
    // const = a name for a value that is never reassigned
    // ...x = spread: copy all items/properties of x into here
    const next = { ...filters, page: 1, ...patch };
    // const = a name for a value that is never reassigned
    // new = create an object from a class (e.g. new Date())
    const search = new URLSearchParams();
    // if (...) = run the next part only when the condition is true
    if (next.status) search.set('status', next.status);
    // if (...) = run the next part only when the condition is true
    if (next.q) search.set('q', next.q);
    // if (...) = run the next part only when the condition is true
    // a && b = AND; in JSX: show b only when a is true
    if (next.page && next.page > 1) search.set('page', String(next.page));
    setParams(search);
  };

  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  // a ?? b = a, unless a is null/undefined, then b
  const [text, setText] = useState(filters.q ?? '');
  // const = a name for a value that is never reassigned
  const debounced = useDebounce(text);
  // useEffect = run code AFTER the screen is drawn (timers, events, browser APIs); re-runs when its [deps] change
  // => = an arrow function (a short function)
  useEffect(() => {
    // if (...) = run the next part only when the condition is true
    // a || b = OR: a if it is truthy, else b
    // !== = not strictly equal
    if ((debounced || undefined) !== filters.q) setFilter({ q: debounced || undefined });
    // eslint-disable-next-line react-hooks/exhaustive-deps -- only react to the debounced text
  }, [debounced]);

  // const = a name for a value that is never reassigned
  // { a, b } = destructuring: take properties a and b out of an object
  // isLoading = first load, no data yet
  // isFetching = a request is running (even if old data is shown)
  // useGetOrdersQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
  const { data, isLoading, isFetching, error } = useGetOrdersQuery(filters);
  // const = a name for a value that is never reassigned
  // { a, b } = destructuring: take properties a and b out of an object
  // x = value (in parameters) = the default used when x is not given
  // useGetOrdersByStatusQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
  const { data: counts = [] } = useGetOrdersByStatusQuery();
  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  // ?. = optional chaining: stop (undefined) instead of crashing if the left side is null/undefined
  // .find = the first item that passes a test (or undefined)
  // === = strictly equal (same value AND same type)
  // a ?? b = a, unless a is null/undefined, then b
  const countOf = (status) => counts.find((c) => c.status === status)?.count ?? 0;
  // const = a name for a value that is never reassigned
  // .reduce = combine all items into one value (e.g. a sum)
  // => = an arrow function (a short function)
  const allCount = counts.reduce((sum, c) => sum + c.count, 0);

  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="space-y-5">
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <h1 className="text-2xl font-bold">Orders</h1>

      {/* Status tabs with counts: "Paid · to ship (2)" is the work queue. */}
      {/* role = tells screen readers what this element is (status, tab, group...)
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div role="tablist" className="flex flex-wrap gap-2">
        {/* { } in JSX = run JavaScript here and show its result
           ! = NOT: flips true/false
           onClick = what happens on click/tap
           => = an arrow function (a short function) */}
        <Tab active={!filters.status} onClick={() => setFilter({ status: undefined })} label="All" count={allCount} />
        {/* { } in JSX = run JavaScript here and show its result
           .map = make a new array by transforming each item (in JSX: one element per item)
           => = an arrow function (a short function) */}
        {statusTabs.map((s) => (
          <Tab
            // key = a stable id for list items so React can track them between redraws
            // { } in JSX = run JavaScript here and show its result
            key={s}
            // { } in JSX = run JavaScript here and show its result
            // === = strictly equal (same value AND same type)
            active={filters.status === s}
            // onClick = what happens on click/tap
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onClick={() => setFilter({ status: s })}
            // { } in JSX = run JavaScript here and show its result
            // obj[key] = read the property whose name is stored in key
            label={statusStyles[s].label}
            // { } in JSX = run JavaScript here and show its result
            count={countOf(s)}
          />
        ))}
      </div>

      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="relative max-w-md">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <Search className="absolute left-3 top-1/2 size-4 -translate-y-1/2 text-slate-400" />
        <input
          // { } in JSX = run JavaScript here and show its result
          value={text}
          // onChange = runs on every change of an input
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          onChange={(e) => setText(e.target.value)}
          // placeholder = grey hint text inside an empty input
          placeholder="Order number (#RHXB9NEJ), customer name or email"
          // aria-label = the name screen readers read for this element
          aria-label="Search orders"
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="w-full rounded-lg border border-slate-300 bg-white py-2 pl-9 pr-3 text-sm outline-none focus:border-brand-500"
        />
      </div>

      {/* { } in JSX = run JavaScript here and show its result
         isLoading = first load, no data yet
         a && b = AND; in JSX: show b only when a is true */}
      {isLoading && <Spinner />}
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {error && <ErrorState message={getErrorMessage(error)} />}
      {/* { } in JSX = run JavaScript here and show its result
         === = strictly equal (same value AND same type)
         a && b = AND; in JSX: show b only when a is true */}
      {data && data.items.length === 0 && <EmptyState title="No orders found" hint="Try another tab or search." />}

      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {data && data.items.length > 0 && (
        <div
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          // { } in JSX = run JavaScript here and show its result
          // `text ${x}` = a template string: text with values inserted
          // a ? b : c = ternary: if a then b else c
          // isFetching = a request is running (even if old data is shown)
          className={`overflow-x-auto rounded-xl border border-slate-200 bg-white ${isFetching ? 'opacity-60' : ''}`}
        >
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <table className="w-full text-sm">
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <thead className="border-b border-slate-200 bg-slate-50 text-left text-xs uppercase tracking-wide text-slate-500">
              <tr>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3">Order</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3">Placed</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3">Customer</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3 text-right">Items</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3 text-right">Total</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3">Status</th>
              </tr>
            </thead>
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <tbody className="divide-y divide-slate-100">
              {/* { } in JSX = run JavaScript here and show its result
                 .map = make a new array by transforming each item (in JSX: one element per item)
                 => = an arrow function (a short function) */}
              {data.items.map((o) => (
                // key = a stable id for list items so React can track them between redraws
                // { } in JSX = run JavaScript here and show its result
                // className = CSS classes (Tailwind) for this element (class is a JS keyword)
                <tr key={o.id} className="hover:bg-slate-50">
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                  <td className="px-4 py-3">
                    {/* Link = a link to another page of this app (no full page reload)
                       { } in JSX = run JavaScript here and show its result
                       `text ${x}` = a template string: text with values inserted
                       className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                    <Link to={`/orders/${o.id}`} className="font-mono font-medium text-brand-700 hover:underline">
                      {/* { } in JSX = run JavaScript here and show its result */}
                      {orderNumber(o.id)}
                    </Link>
                  </td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                     { } in JSX = run JavaScript here and show its result */}
                  <td className="px-4 py-3 text-slate-600">{formatDateTime(o.createdAt)}</td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                  <td className="px-4 py-3">
                    {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                       { } in JSX = run JavaScript here and show its result */}
                    <p className="font-medium">{o.user.name}</p>
                    {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                       { } in JSX = run JavaScript here and show its result */}
                    <p className="text-xs text-slate-500">{o.user.email}</p>
                  </td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                     { } in JSX = run JavaScript here and show its result */}
                  <td className="px-4 py-3 text-right">{o._count.items}</td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                     { } in JSX = run JavaScript here and show its result */}
                  <td className="px-4 py-3 text-right font-medium">{formatPrice(o.total)}</td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                  <td className="px-4 py-3">
                    {/* { } in JSX = run JavaScript here and show its result */}
                    <OrderStatusBadge status={o.status} />
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {data && data.totalPages > 1 && (
        // className = CSS classes (Tailwind) for this element (class is a JS keyword)
        <div className="flex items-center justify-end gap-3">
          {/* disabled = can't be clicked or typed in
             { } in JSX = run JavaScript here and show its result
             onClick = what happens on click/tap
             => = an arrow function (a short function) */}
          <Button variant="secondary" disabled={data.page <= 1} onClick={() => setFilter({ page: data.page - 1 })}>
            Previous
          </Button>
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <span className="text-sm text-slate-500">
            Page {data.page} of {data.totalPages}
          </span>
          <Button
            variant="secondary"
            // disabled = can't be clicked or typed in
            // { } in JSX = run JavaScript here and show its result
            disabled={data.page >= data.totalPages}
            // onClick = what happens on click/tap
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onClick={() => setFilter({ page: data.page + 1 })}
          >
            Next
          </Button>
        </div>
      )}
    </div>
  );
}

// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
// onClick = what happens on click/tap
function Tab({ active, onClick, label, count }) {
  // return = give this value back and stop the function here
  return (
    <button
      // role = tells screen readers what this element is (status, tab, group...)
      role="tab"
      // aria-selected = which tab/option is selected
      // { } in JSX = run JavaScript here and show its result
      aria-selected={active}
      // onClick = what happens on click/tap
      // { } in JSX = run JavaScript here and show its result
      onClick={onClick}
      // className = CSS classes (Tailwind) for this element (class is a JS keyword)
      // { } in JSX = run JavaScript here and show its result
      // `text ${x}` = a template string: text with values inserted
      // a ? b : c = ternary: if a then b else c
      className={`flex items-center gap-1.5 rounded-full px-3 py-1.5 text-sm font-medium ${active ? 'bg-slate-900 text-white' : 'bg-white text-slate-700 ring-1 ring-slate-200 hover:bg-slate-50'}`}
    >
      {/* { } in JSX = run JavaScript here and show its result
         className = CSS classes (Tailwind) for this element (class is a JS keyword)
         `text ${x}` = a template string: text with values inserted
         a ? b : c = ternary: if a then b else c */}
      {label} <span className={`text-xs ${active ? 'text-slate-300' : 'text-slate-400'}`}>{count}</span>
    </button>
  );
}
