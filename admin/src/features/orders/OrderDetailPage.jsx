// PAID -> SHIPPED -> DELIVERED, with the current step highlighted.
// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
function Progress({ status }) {
  // if (...) = run the next part only when the condition is true
  // ! = NOT: flips true/false
  // .includes = true if the array/string contains the value
  // return = give this value back and stop the function here
  if (!['PAID', 'SHIPPED', 'DELIVERED'].includes(status)) return null;
  // const = a name for a value that is never reassigned
  const steps = [
    { key: 'PAID', label: 'Paid', icon: Check },
    { key: 'SHIPPED', label: 'Shipped', icon: Truck },
    { key: 'DELIVERED', label: 'Delivered', icon: PackageCheck },
  ];
  // const = a name for a value that is never reassigned
  // .findIndex = the position of the first matching item (-1 if none)
  // => = an arrow function (a short function)
  // === = strictly equal (same value AND same type)
  const current = steps.findIndex((s) => s.key === status);
  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <ol className="flex items-center gap-2 rounded-xl border border-slate-200 bg-white p-4">
      {/* { } in JSX = run JavaScript here and show its result
         .map = make a new array by transforming each item (in JSX: one element per item)
         => = an arrow function (a short function)
         { a, b } = destructuring: take properties a and b out of an object */}
      {steps.map(({ key, label, icon: Icon }, i) => (
        // key = a stable id for list items so React can track them between redraws
        // { } in JSX = run JavaScript here and show its result
        // className = CSS classes (Tailwind) for this element (class is a JS keyword)
        <li key={key} className="flex flex-1 items-center gap-2">
          <span
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            // { } in JSX = run JavaScript here and show its result
            // `text ${x}` = a template string: text with values inserted
            // a ? b : c = ternary: if a then b else c
            className={`flex size-8 items-center justify-center rounded-full ${i <= current ? 'bg-brand-600 text-white' : 'bg-slate-200 text-slate-400'}`}
          >
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <Icon className="size-4" />
          </span>
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
             { } in JSX = run JavaScript here and show its result
             `text ${x}` = a template string: text with values inserted
             a ? b : c = ternary: if a then b else c */}
          <span className={`text-sm font-medium ${i <= current ? 'text-slate-900' : 'text-slate-400'}`}>{label}</span>
          {/* { } in JSX = run JavaScript here and show its result
             a && b = AND; in JSX: show b only when a is true
             className = CSS classes (Tailwind) for this element (class is a JS keyword)
             `text ${x}` = a template string: text with values inserted
             a ? b : c = ternary: if a then b else c */}
          {i < steps.length - 1 && <span className={`h-0.5 flex-1 ${i < current ? 'bg-brand-600' : 'bg-slate-200'}`} />}
        </li>
      ))}
    </ol>
  );
}

// Only the actions the order's current state allows are shown. The backend enforces the same rules.
// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
function Actions({ order }) {
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useUpdateOrderStatusMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [updateStatus, statusState] = useUpdateOrderStatusMutation();
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useRefundOrderMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [refund, refundState] = useRefundOrderMutation();
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [refundOpen, setRefundOpen] = useState(false);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [restock, setRestock] = useState(false);
  // const = a name for a value that is never reassigned
  // a ?? b = a, unless a is null/undefined, then b
  const error = statusState.error ?? refundState.error;
  // const = a name for a value that is never reassigned
  // .includes = true if the array/string contains the value
  // a && b = AND; in JSX: show b only when a is true
  // !!x = turn any value into true/false
  // ! = NOT: flips true/false
  const canRefund = REFUNDABLE.includes(order.status) && !!order.stripePaymentIntentId;

  // const = a name for a value that is never reassigned
  const next =
    // a ? b : c = ternary: if a then b else c
    // === = strictly equal (same value AND same type)
    order.status === 'PAID'
      ? { to: 'SHIPPED', label: 'Mark as shipped', icon: Truck }
      // a ? b : c = ternary: if a then b else c
      // === = strictly equal (same value AND same type)
      : order.status === 'SHIPPED'
        ? { to: 'DELIVERED', label: 'Mark as delivered', icon: PackageCheck }
        : null;

  // return = give this value back and stop the function here
  return (
    <Box title="Actions">
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {error && (
        // className = CSS classes (Tailwind) for this element (class is a JS keyword)
        <div className="mb-3">
          {/* { } in JSX = run JavaScript here and show its result */}
          <ErrorState message={getErrorMessage(error)} />
        </div>
      )}
      {/* { } in JSX = run JavaScript here and show its result
         ! = NOT: flips true/false
         a && b = AND; in JSX: show b only when a is true */}
      {!next && !canRefund && (
        // className = CSS classes (Tailwind) for this element (class is a JS keyword)
        // { } in JSX = run JavaScript here and show its result
        <p className="text-sm text-slate-500">No actions for a {order.status.toLowerCase()} order.</p>
      )}

      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="space-y-2">
        {/* { } in JSX = run JavaScript here and show its result
           a && b = AND; in JSX: show b only when a is true */}
        {next && (
          <Button
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="w-full"
            // loading="lazy" = load the image only when it gets near the screen
            // { } in JSX = run JavaScript here and show its result
            // isLoading = first load, no data yet
            loading={statusState.isLoading}
            // onClick = what happens on click/tap
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onClick={() => updateStatus({ id: order.id, status: next.to })}
          >
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
               { } in JSX = run JavaScript here and show its result */}
            <next.icon className="size-4" /> {next.label}
          </Button>
        )}

        {/* { } in JSX = run JavaScript here and show its result
           ! = NOT: flips true/false
           a && b = AND; in JSX: show b only when a is true */}
        {canRefund && !refundOpen && (
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          // onClick = what happens on click/tap
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          <Button variant="secondary" className="w-full" onClick={() => setRefundOpen(true)}>
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <RotateCcw className="size-4" /> Refund
          </Button>
        )}

        {/* { } in JSX = run JavaScript here and show its result
           a && b = AND; in JSX: show b only when a is true */}
        {canRefund && refundOpen && (
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          <div className="space-y-3 rounded-lg border border-red-200 bg-red-50 p-3">
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <p className="text-sm font-medium text-red-900">
              Refund {formatPrice(order.total)} to the customer's card?
            </p>
            {/* <label> = the name of an input; clicking it focuses the input
               className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <label className="flex cursor-pointer items-start gap-2 text-sm text-red-900">
              <input
                type="checkbox"
                // { } in JSX = run JavaScript here and show its result
                checked={restock}
                // onChange = runs on every change of an input
                // { } in JSX = run JavaScript here and show its result
                // => = an arrow function (a short function)
                onChange={(e) => setRestock(e.target.checked)}
                // className = CSS classes (Tailwind) for this element (class is a JS keyword)
                className="mt-0.5"
              />
              <span>Put the items back in stock (only if they were returned unused)</span>
            </label>
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <div className="flex gap-2">
              <Button
                variant="danger"
                // loading="lazy" = load the image only when it gets near the screen
                // { } in JSX = run JavaScript here and show its result
                // isLoading = first load, no data yet
                loading={refundState.isLoading}
                // onClick = what happens on click/tap
                // { } in JSX = run JavaScript here and show its result
                // => = an arrow function (a short function)
                // async = this function works with await and returns a Promise
                onClick={async () => {
                  // await = wait for a Promise (async result) before continuing
                  await refund({ id: order.id, restock })
                    // .unwrap() = turn the mutation result into a normal Promise: returns data or throws the error
                    .unwrap()
                    // => = an arrow function (a short function)
                    .catch(() => undefined);
                  setRefundOpen(false);
                }}
              >
                Confirm refund
              </Button>
              {/* onClick = what happens on click/tap
                 { } in JSX = run JavaScript here and show its result
                 => = an arrow function (a short function) */}
              <Button variant="ghost" onClick={() => setRefundOpen(false)}>
                Cancel
              </Button>
            </div>
          </div>
        )}
      </div>
    </Box>
  );
}

