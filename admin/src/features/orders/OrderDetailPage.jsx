function InvoiceActions({ order }) {
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [busy, setBusy] = useState(false);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [error, setError] = useState(null);
  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  // async = this function works with await and returns a Promise
  const download = async () => {
    setBusy(true);
    setError(null);
    // try / catch = if the code inside fails, run the catch part instead of crashing
    try {
      // await = wait for a Promise (async result) before continuing
      // `text ${x}` = a template string: text with values inserted
      await downloadFile(`/admin/orders/${order.id}/invoice`, `${order.invoiceLabel}.pdf`);
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  };
  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="mt-3 space-y-2 border-t border-slate-100 pt-3">
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <p className="text-xs text-slate-500">
        Invoice <span className="font-mono text-slate-700">{order.invoiceLabel}</span>
      </p>
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="flex flex-wrap gap-2">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
           loading="lazy" = load the image only when it gets near the screen
           { } in JSX = run JavaScript here and show its result
           onClick = what happens on click/tap */}
        <Button variant="secondary" className="px-3 py-1.5 text-xs" loading={busy} onClick={download}>
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <Download className="size-3.5" /> Download invoice
        </Button>
        {/* { } in JSX = run JavaScript here and show its result
           a && b = AND; in JSX: show b only when a is true */}
        {order.receiptUrl && (
          <a
            // { } in JSX = run JavaScript here and show its result
            href={order.receiptUrl}
            target="_blank"
            rel="noreferrer"
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="inline-flex items-center gap-1 px-2 py-1.5 text-xs text-brand-700 hover:underline"
          >
            Stripe receipt <ExternalLink className="size-3" />
          </a>
        )}
      </div>
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {error && <ErrorState message={error} />}
    </div>
  );
}
