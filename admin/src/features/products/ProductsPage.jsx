// import = bring in code from another file or package
// useEffect = run code AFTER the screen is drawn (timers, events, browser APIs); re-runs when its [deps] change
// useState = a value the component remembers; calling its setter redraws the component
import { useEffect, useState } from 'react';
// import = bring in code from another file or package
// Link = a link to another page of this app (no full page reload)
// useSearchParams = read/write the ?query=part of the URL
import { Link, useSearchParams } from 'react-router';
// import = bring in code from another file or package
import { AlertTriangle, Plus, Search } from 'lucide-react';
// import = bring in code from another file or package
import { Button } from '@/components/ui/Button';
// import = bring in code from another file or package
import { EmptyState, ErrorState, Spinner } from '@/components/ui/States';
// import = bring in code from another file or package
import { formatPrice, getErrorMessage } from '@/lib/format';
// import = bring in code from another file or package
import { useDebounce } from '@/lib/use-debounce';
// import = bring in code from another file or package
// useGetCategoriesQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
// useGetProductsQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
import { useGetCategoriesQuery, useGetProductsQuery } from './productsApi';

// export = other files can import this
// function Name() = a React component (capital letter): returns what to show (JSX)
export function ProductsPage() {
  // Filters live in the URL (?q=nike&status=hidden&page=2): shareable, and the back button works.
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useSearchParams = read/write the ?query=part of the URL
  const [params, setParams] = useSearchParams();
  // const = a name for a value that is never reassigned
  const filters = {
    // a ?? b = a, unless a is null/undefined, then b
    q: params.get('q') ?? undefined,
    // a ?? b = a, unless a is null/undefined, then b
    category: params.get('category') ?? undefined,
    // a ?? b = a, unless a is null/undefined, then b
    status: params.get('status') ?? 'all',
    // === = strictly equal (same value AND same type)
    lowStock: params.get('lowStock') === 'true',
    // a ?? b = a, unless a is null/undefined, then b
    page: Number(params.get('page') ?? 1),
  };

  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  const setFilter = (patch) => {
    // const = a name for a value that is never reassigned
    // ...x = spread: copy all items/properties of x into here
    const next = { ...filters, page: 1, ...patch }; // changing a filter goes back to page 1
    // const = a name for a value that is never reassigned
    // new = create an object from a class (e.g. new Date())
    const search = new URLSearchParams();
    // if (...) = run the next part only when the condition is true
    if (next.q) search.set('q', next.q);
    // if (...) = run the next part only when the condition is true
    if (next.category) search.set('category', next.category);
    // if (...) = run the next part only when the condition is true
    // a && b = AND; in JSX: show b only when a is true
    // !== = not strictly equal
    if (next.status && next.status !== 'all') search.set('status', next.status);
    // if (...) = run the next part only when the condition is true
    if (next.lowStock) search.set('lowStock', 'true');
    // if (...) = run the next part only when the condition is true
    // a && b = AND; in JSX: show b only when a is true
    if (next.page && next.page > 1) search.set('page', String(next.page));
    setParams(search);
  };

  // The search box updates the URL only after typing pauses.
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  // a ?? b = a, unless a is null/undefined, then b
  const [text, setText] = useState(filters.q ?? '');
  // const = a name for a value that is never reassigned
  const debounced = useDebounce(text);
  // useEffect = run code AFTER the screen is drawn (timers, events, browser APIs); re-runs when its [deps] change
  // => = an arrow function (a short function)
  useEffect(() => {
    // if (...) = run the next part only when the condition is true
    // a || b = OR: a if it is truthy, else b
    // !== = not strictly equal
    if ((debounced || undefined) !== filters.q) setFilter({ q: debounced || undefined });
    // eslint-disable-next-line react-hooks/exhaustive-deps -- only react to the debounced text
  }, [debounced]);

  // const = a name for a value that is never reassigned
  // { a, b } = destructuring: take properties a and b out of an object
  // isLoading = first load, no data yet
  // isFetching = a request is running (even if old data is shown)
  // useGetProductsQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
  const { data, isLoading, isFetching, error } = useGetProductsQuery(filters);
  // const = a name for a value that is never reassigned
  // { a, b } = destructuring: take properties a and b out of an object
  // x = value (in parameters) = the default used when x is not given
  // useGetCategoriesQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
  const { data: categories = [] } = useGetCategoriesQuery();

  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="space-y-5">
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="flex items-center justify-between">
        <div>
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <h1 className="text-2xl font-bold">Products</h1>
          {/* { } in JSX = run JavaScript here and show its result
             a && b = AND; in JSX: show b only when a is true
             className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          {data && <p className="text-sm text-slate-500">{data.total} products</p>}
        </div>
        {/* Link = a link to another page of this app (no full page reload) */}
        <Link to="/products/new">
          <Button>
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <Plus className="size-4" /> New product
          </Button>
        </Link>
      </div>

      {/* Filters */}
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="flex flex-wrap items-center gap-3 rounded-xl border border-slate-200 bg-white p-3">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <div className="relative min-w-60 flex-1">
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <Search className="absolute left-3 top-1/2 size-4 -translate-y-1/2 text-slate-400" />
          <input
            // { } in JSX = run JavaScript here and show its result
            value={text}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setText(e.target.value)}
            // placeholder = grey hint text inside an empty input
            placeholder="Search name, brand or SKU"
            // aria-label = the name screen readers read for this element
            aria-label="Search products"
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="w-full rounded-lg border border-slate-300 py-2 pl-9 pr-3 text-sm outline-none focus:border-brand-500"
          />
        </div>
        {/* <select> = a dropdown list */}
        <select
          // { } in JSX = run JavaScript here and show its result
          // a ?? b = a, unless a is null/undefined, then b
          value={filters.category ?? ''}
          // onChange = runs on every change of an input
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          // a || b = OR: a if it is truthy, else b
          onChange={(e) => setFilter({ category: e.target.value || undefined })}
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="rounded-lg border border-slate-300 px-3 py-2 text-sm"
          // aria-label = the name screen readers read for this element
          aria-label="Category"
        >
          <option value="">All categories</option>
          {/* { } in JSX = run JavaScript here and show its result
             .map = make a new array by transforming each item (in JSX: one element per item)
             => = an arrow function (a short function) */}
          {categories.map((c) => (
            // key = a stable id for list items so React can track them between redraws
            // { } in JSX = run JavaScript here and show its result
            <option key={c.id} value={c.slug}>
              {/* { } in JSX = run JavaScript here and show its result */}
              {c.name}
            </option>
          ))}
        </select>
        {/* <select> = a dropdown list */}
        <select
          // { } in JSX = run JavaScript here and show its result
          value={filters.status}
          // onChange = runs on every change of an input
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          onChange={(e) => setFilter({ status: e.target.value })}
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="rounded-lg border border-slate-300 px-3 py-2 text-sm"
          // aria-label = the name screen readers read for this element
          aria-label="Status"
        >
          <option value="all">All statuses</option>
          <option value="active">Active</option>
          <option value="hidden">Hidden</option>
        </select>
        {/* <label> = the name of an input; clicking it focuses the input
           className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <label className="flex cursor-pointer items-center gap-2 text-sm">
          <input
            type="checkbox"
            // { } in JSX = run JavaScript here and show its result
            checked={filters.lowStock}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setFilter({ lowStock: e.target.checked })}
          />
          Low stock only
        </label>
      </div>

      {/* { } in JSX = run JavaScript here and show its result
         isLoading = first load, no data yet
         a && b = AND; in JSX: show b only when a is true */}
      {isLoading && <Spinner />}
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {error && <ErrorState message={getErrorMessage(error)} />}
      {/* { } in JSX = run JavaScript here and show its result
         === = strictly equal (same value AND same type)
         a && b = AND; in JSX: show b only when a is true */}
      {data && data.items.length === 0 && <EmptyState title="No products found" hint="Try different filters." />}

      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {data && data.items.length > 0 && (
        <div
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          // { } in JSX = run JavaScript here and show its result
          // `text ${x}` = a template string: text with values inserted
          // a ? b : c = ternary: if a then b else c
          // isFetching = a request is running (even if old data is shown)
          className={`overflow-x-auto rounded-xl border border-slate-200 bg-white ${isFetching ? 'opacity-60' : ''}`}
        >
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <table className="w-full text-sm">
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <thead className="border-b border-slate-200 bg-slate-50 text-left text-xs uppercase tracking-wide text-slate-500">
              <tr>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3">Product</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3">Category</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3 text-right">Price from</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3 text-right">Stock</th>
                {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                <th className="px-4 py-3">Status</th>
              </tr>
            </thead>
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <tbody className="divide-y divide-slate-100">
              {/* { } in JSX = run JavaScript here and show its result
                 .map = make a new array by transforming each item (in JSX: one element per item)
                 => = an arrow function (a short function) */}
              {data.items.map((p) => (
                // key = a stable id for list items so React can track them between redraws
                // { } in JSX = run JavaScript here and show its result
                // className = CSS classes (Tailwind) for this element (class is a JS keyword)
                <tr key={p.id} className="hover:bg-slate-50">
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                  <td className="px-4 py-3">
                    {/* Link = a link to another page of this app (no full page reload)
                       { } in JSX = run JavaScript here and show its result
                       `text ${x}` = a template string: text with values inserted
                       className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                    <Link to={`/products/${p.id}`} className="flex items-center gap-3">
                      {/* { } in JSX = run JavaScript here and show its result
                         alt = text describing the image for screen readers (empty = decorative)
                         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                      <img src={p.images[0]} alt="" className="size-10 rounded-lg bg-slate-100 object-cover" />
                      <div>
                        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                           { } in JSX = run JavaScript here and show its result */}
                        <p className="font-medium text-slate-900 hover:underline">{p.name}</p>
                        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                        <p className="text-xs text-slate-500">
                          {/* { } in JSX = run JavaScript here and show its result
                             a ?? b = a, unless a is null/undefined, then b
                             a ? b : c = ternary: if a then b else c
                             === = strictly equal (same value AND same type) */}
                          {p.brand ?? 'No brand'} · {p.variants.length} variant{p.variants.length === 1 ? '' : 's'}
                        </p>
                      </div>
                    </Link>
                  </td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                     { } in JSX = run JavaScript here and show its result */}
                  <td className="px-4 py-3 text-slate-600">{p.category.name}</td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
                     { } in JSX = run JavaScript here and show its result */}
                  <td className="px-4 py-3 text-right">{formatPrice(p.basePrice)}</td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                  <td className="px-4 py-3 text-right">
                    <span
                      // className = CSS classes (Tailwind) for this element (class is a JS keyword)
                      // { } in JSX = run JavaScript here and show its result
                      // `text ${x}` = a template string: text with values inserted
                      // a ? b : c = ternary: if a then b else c
                      className={`inline-flex items-center gap-1 ${p.lowStock ? 'font-medium text-amber-700' : ''}`}
                    >
                      {/* { } in JSX = run JavaScript here and show its result
                         a && b = AND; in JSX: show b only when a is true
                         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                      {p.lowStock && <AlertTriangle className="size-3.5" />} {p.totalStock}
                    </span>
                  </td>
                  {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
                  <td className="px-4 py-3">
                    <span
                      // className = CSS classes (Tailwind) for this element (class is a JS keyword)
                      // { } in JSX = run JavaScript here and show its result
                      // `text ${x}` = a template string: text with values inserted
                      // a ? b : c = ternary: if a then b else c
                      className={`rounded-full px-2 py-0.5 text-xs font-semibold ${p.isActive ? 'bg-green-100 text-green-800' : 'bg-slate-200 text-slate-600'}`}
                    >
                      {/* { } in JSX = run JavaScript here and show its result
                         a ? b : c = ternary: if a then b else c */}
                      {p.isActive ? 'Active' : 'Hidden'}
                    </span>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {data && data.totalPages > 1 && (
        // className = CSS classes (Tailwind) for this element (class is a JS keyword)
        <div className="flex items-center justify-end gap-3">
          {/* disabled = can't be clicked or typed in
             { } in JSX = run JavaScript here and show its result
             onClick = what happens on click/tap
             => = an arrow function (a short function) */}
          <Button variant="secondary" disabled={data.page <= 1} onClick={() => setFilter({ page: data.page - 1 })}>
            Previous
          </Button>
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <span className="text-sm text-slate-500">
            Page {data.page} of {data.totalPages}
          </span>
          <Button
            variant="secondary"
            // disabled = can't be clicked or typed in
            // { } in JSX = run JavaScript here and show its result
            disabled={data.page >= data.totalPages}
            // onClick = what happens on click/tap
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onClick={() => setFilter({ page: data.page + 1 })}
          >
            Next
          </Button>
        </div>
      )}
    </div>
  );
}
