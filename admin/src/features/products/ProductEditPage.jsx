// useCreateProductMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
// useGetProductQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
// useUpdateProductMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
import { useCreateProductMutation, useGetProductQuery, useUpdateProductMutation } from './productsApi';

// /products/:id: edit an existing product.
// export = other files can import this
// function Name() = a React component (capital letter): returns what to show (JSX)
export function ProductEditPage() {
  // const = a name for a value that is never reassigned
  // { a, b } = destructuring: take properties a and b out of an object
  // x = value (in parameters) = the default used when x is not given
  // useParams = the :parts of the URL, e.g. :slug in /products/:slug
  const { id = '' } = useParams();
  // const = a name for a value that is never reassigned
  // { a, b } = destructuring: take properties a and b out of an object
  // isLoading = first load, no data yet
  // useGetProductQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
  const { data: product, isLoading, error } = useGetProductQuery(id);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useUpdateProductMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [update, updateState] = useUpdateProductMutation();

  // if (...) = run the next part only when the condition is true
  // isLoading = first load, no data yet
  // return = give this value back and stop the function here
  if (isLoading) return <Spinner />;
  // if (...) = run the next part only when the condition is true
  // a || b = OR: a if it is truthy, else b
  // ! = NOT: flips true/false
  // return = give this value back and stop the function here
  // { } in JSX = run JavaScript here and show its result
  if (error || !product) return <ErrorState message={getErrorMessage(error)} />;

  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="mx-auto max-w-4xl space-y-5">
      {/* Link = a link to another page of this app (no full page reload)
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <Link to="/products" className="inline-flex items-center gap-1 text-sm text-slate-500 hover:underline">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <ArrowLeft className="size-4" /> Products
      </Link>
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="flex items-start justify-between gap-4">
        <div>
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
             { } in JSX = run JavaScript here and show its result */}
          <h1 className="text-2xl font-bold">{product.name}</h1>
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <p className="text-sm text-slate-500">
            /products/{product.slug} · ⭐ {product.ratingAvg.toFixed(1)} ({product.ratingCount} reviews)
          </p>
        </div>
        {/* { } in JSX = run JavaScript here and show its result
           a && b = AND; in JSX: show b only when a is true */}
        {product.isActive && (
          // { } in JSX = run JavaScript here and show its result
          // `text ${x}` = a template string: text with values inserted
          <a href={`${STORE_URL}/products/${product.slug}`} target="_blank" rel="noreferrer">
            <Button variant="secondary">
              {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
              <ExternalLink className="size-4" /> View in store
            </Button>
          </a>
        )}
      </div>

      {/* { } in JSX = run JavaScript here and show its result
         isSuccess = the request finished fine
         a && b = AND; in JSX: show b only when a is true
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      {updateState.isSuccess && <p className="rounded-lg bg-green-50 p-3 text-sm text-green-800">Saved.</p>}
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {updateState.error && <ErrorState message={getErrorMessage(updateState.error)} />}

      {/* key: after saving, re-create the form from the fresh product data */}
      <ProductForm
        // key = a stable id for list items so React can track them between redraws
        // { } in JSX = run JavaScript here and show its result
        key={product.updatedAt}
        // { } in JSX = run JavaScript here and show its result
        product={product}
        submitLabel="Save details"
        // { } in JSX = run JavaScript here and show its result
        // isLoading = first load, no data yet
        saving={updateState.isLoading}
        // onSubmit = runs when the form is sent (Enter or submit button)
        // { } in JSX = run JavaScript here and show its result
        // => = an arrow function (a short function)
        // ...x = spread: copy all items/properties of x into here
        onSubmit={(input) => update({ id: product.id, ...input })}
      />

      {/* { } in JSX = run JavaScript here and show its result */}
      <VariantsManager product={product} />
    </div>
  );
}

// /products/new: create a product together with its first variants.
// export = other files can import this
// function Name() = a React component (capital letter): returns what to show (JSX)
export function ProductCreatePage() {
  // const = a name for a value that is never reassigned
  // useNavigate = gives navigate(url) to change page from code
  const navigate = useNavigate();
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // { a, b } = destructuring: take properties a and b out of an object
  // isLoading = first load, no data yet
  // useCreateProductMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [create, { isLoading, error }] = useCreateProductMutation();
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [variants, setVariants] = useState([{ sku: '', name: '', price: '', stock: '0' }]);

  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  // .map = make a new array by transforming each item (in JSX: one element per item)
  // a ? b : c = ternary: if a then b else c
  // === = strictly equal (same value AND same type)
  // ...x = spread: copy all items/properties of x into here
  const setVariant = (i, patch) => setVariants((rows) => rows.map((r, j) => (j === i ? { ...r, ...patch } : r)));

  // const = a name for a value that is never reassigned
  const variantsEditor = (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="space-y-3 rounded-xl border border-slate-200 bg-white p-5">
      <div>
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <h2 className="font-semibold">Variants</h2>
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <p className="text-sm text-slate-500">
          Each size/colour/edition customers can pick, with its own SKU, price and starting stock.
        </p>
      </div>
      {/* { } in JSX = run JavaScript here and show its result
         .map = make a new array by transforming each item (in JSX: one element per item)
         => = an arrow function (a short function) */}
      {variants.map((v, i) => (
        // key = a stable id for list items so React can track them between redraws
        // { } in JSX = run JavaScript here and show its result
        // className = CSS classes (Tailwind) for this element (class is a JS keyword)
        <div key={i} className="flex flex-wrap gap-2">
          <input
            // required = the browser won't submit the form while this is empty
            required
            // placeholder = grey hint text inside an empty input
            placeholder="SKU"
            // { } in JSX = run JavaScript here and show its result
            value={v.sku}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setVariant(i, { sku: e.target.value })}
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="w-40 rounded border border-slate-300 px-2 py-1.5 text-sm"
          />
          <input
            // required = the browser won't submit the form while this is empty
            required
            // placeholder = grey hint text inside an empty input
            placeholder="Name, e.g. UK 9 / Black"
            // { } in JSX = run JavaScript here and show its result
            value={v.name}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setVariant(i, { name: e.target.value })}
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="flex-1 rounded border border-slate-300 px-2 py-1.5 text-sm"
          />
          <input
            // required = the browser won't submit the form while this is empty
            required
            // placeholder = grey hint text inside an empty input
            placeholder="Price $"
            type="number"
            min="0.01"
            step="0.01"
            // { } in JSX = run JavaScript here and show its result
            value={v.price}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setVariant(i, { price: e.target.value })}
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="w-28 rounded border border-slate-300 px-2 py-1.5 text-sm"
          />
          <input
            // required = the browser won't submit the form while this is empty
            required
            // placeholder = grey hint text inside an empty input
            placeholder="Stock"
            type="number"
            min="0"
            step="1"
            // { } in JSX = run JavaScript here and show its result
            value={v.stock}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setVariant(i, { stock: e.target.value })}
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="w-20 rounded border border-slate-300 px-2 py-1.5 text-sm"
          />
          <button
            type="button"
            // disabled = can't be clicked or typed in
            // { } in JSX = run JavaScript here and show its result
            // === = strictly equal (same value AND same type)
            disabled={variants.length === 1}
            // onClick = what happens on click/tap
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            // .filter = keep only the items that pass a test
            // !== = not strictly equal
            onClick={() => setVariants((rows) => rows.filter((_, j) => j !== i))}
            // aria-label = the name screen readers read for this element
            aria-label="Remove variant row"
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="rounded p-1.5 text-slate-400 hover:text-red-600 disabled:opacity-30"
          >
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <Trash2 className="size-4" />
          </button>
        </div>
      ))}
      <Button
        type="button"
        variant="ghost"
        // onClick = what happens on click/tap
        // { } in JSX = run JavaScript here and show its result
        // => = an arrow function (a short function)
        // ...x = spread: copy all items/properties of x into here
        onClick={() => setVariants((rows) => [...rows, { sku: '', name: '', price: '', stock: '0' }])}
      >
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <Plus className="size-4" /> Add another variant
      </Button>
    </div>
  );

  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="mx-auto max-w-4xl space-y-5">
      {/* Link = a link to another page of this app (no full page reload)
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <Link to="/products" className="inline-flex items-center gap-1 text-sm text-slate-500 hover:underline">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <ArrowLeft className="size-4" /> Products
      </Link>
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <h1 className="text-2xl font-bold">New product</h1>
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {error && <ErrorState message={getErrorMessage(error)} />}
      <ProductForm
        submitLabel="Create product"
        // { } in JSX = run JavaScript here and show its result
        // isLoading = first load, no data yet
        saving={isLoading}
        // { } in JSX = run JavaScript here and show its result
        extra={variantsEditor}
        // onSubmit = runs when the form is sent (Enter or submit button)
        // { } in JSX = run JavaScript here and show its result
        // => = an arrow function (a short function)
        // async = this function works with await and returns a Promise
        onSubmit={async (input) => {
          // const = a name for a value that is never reassigned
          // await = wait for a Promise (async result) before continuing
          const product = await create({
            // ...x = spread: copy all items/properties of x into here
            ...input,
            // .map = make a new array by transforming each item (in JSX: one element per item)
            // => = an arrow function (a short function)
            variants: variants.map((v) => ({
              sku: v.sku,
              name: v.name,
              price: toCents(v.price),
              stock: Number(v.stock),
            })),
          })
            // .unwrap() = turn the mutation result into a normal Promise: returns data or throws the error
            .unwrap()
            // => = an arrow function (a short function)
            .catch(() => null);
          // if (...) = run the next part only when the condition is true
          // `text ${x}` = a template string: text with values inserted
          if (product) navigate(`/products/${product.id}`);
        }}
      />
    </div>
  );
}
