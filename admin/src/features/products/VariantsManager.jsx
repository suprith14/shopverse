// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
function VariantRow({ productId, variant }) {
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [name, setName] = useState(variant.name);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [price, setPrice] = useState(toDollars(variant.price));
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [delta, setDelta] = useState('');
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useUpdateVariantMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [update, updateState] = useUpdateVariantMutation();
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useAdjustStockMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [adjust, adjustState] = useAdjustStockMutation();
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useDeleteVariantMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [remove, removeState] = useDeleteVariantMutation();

  // const = a name for a value that is never reassigned
  // !== = not strictly equal
  // a || b = OR: a if it is truthy, else b
  const changed = name !== variant.name || toCents(price) !== variant.price;
  // const = a name for a value that is never reassigned
  // a ?? b = a, unless a is null/undefined, then b
  const error = updateState.error ?? adjustState.error ?? removeState.error;
  // const = a name for a value that is never reassigned
  const deltaNumber = Number(delta);

  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  // async = this function works with await and returns a Promise
  const applyStock = async (amount) => {
    // await = wait for a Promise (async result) before continuing
    await adjust({ productId, variantId: variant.id, delta: amount })
      // .unwrap() = turn the mutation result into a normal Promise: returns data or throws the error
      .unwrap()
      // => = an arrow function (a short function)
      .catch(() => undefined);
    setDelta('');
  };

  // return = give this value back and stop the function here
  return (
    // <> </> = a fragment: groups elements without adding an extra HTML element
    <>
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <tr className="align-top">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
           { } in JSX = run JavaScript here and show its result */}
        <td className="px-4 py-3 font-mono text-xs text-slate-600">{variant.sku}</td>
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <td className="px-4 py-3">
          <input
            // { } in JSX = run JavaScript here and show its result
            value={name}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setName(e.target.value)}
            // aria-label = the name screen readers read for this element
            aria-label="Variant name"
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="w-full rounded border border-slate-300 px-2 py-1"
          />
        </td>
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <td className="px-4 py-3">
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <div className="flex items-center gap-2">
            <input
              type="number"
              min="0.01"
              step="0.01"
              // { } in JSX = run JavaScript here and show its result
              value={price}
              // onChange = runs on every change of an input
              // { } in JSX = run JavaScript here and show its result
              // => = an arrow function (a short function)
              onChange={(e) => setPrice(e.target.value)}
              // aria-label = the name screen readers read for this element
              aria-label="Price in dollars"
              // className = CSS classes (Tailwind) for this element (class is a JS keyword)
              className="w-24 rounded border border-slate-300 px-2 py-1"
            />
            {/* { } in JSX = run JavaScript here and show its result
               a && b = AND; in JSX: show b only when a is true */}
            {changed && (
              <Button
                variant="secondary"
                // className = CSS classes (Tailwind) for this element (class is a JS keyword)
                className="px-2 py-1 text-xs"
                // loading="lazy" = load the image only when it gets near the screen
                // { } in JSX = run JavaScript here and show its result
                // isLoading = first load, no data yet
                loading={updateState.isLoading}
                // onClick = what happens on click/tap
                // { } in JSX = run JavaScript here and show its result
                // => = an arrow function (a short function)
                onClick={() => update({ productId, variantId: variant.id, name, price: toCents(price) })}
              >
                Save
              </Button>
            )}
          </div>
        </td>
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <td className="px-4 py-3">
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <div className="flex items-center gap-2">
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword)
               { } in JSX = run JavaScript here and show its result
               `text ${x}` = a template string: text with values inserted
               a ? b : c = ternary: if a then b else c */}
            <span className={`w-10 font-semibold ${variant.stock <= 5 ? 'text-amber-700' : ''}`}>{variant.stock}</span>
            <input
              type="number"
              step="1"
              // { } in JSX = run JavaScript here and show its result
              value={delta}
              // onChange = runs on every change of an input
              // { } in JSX = run JavaScript here and show its result
              // => = an arrow function (a short function)
              onChange={(e) => setDelta(e.target.value)}
              // placeholder = grey hint text inside an empty input
              placeholder="±"
              // aria-label = the name screen readers read for this element
              aria-label="Units to add or remove"
              // className = CSS classes (Tailwind) for this element (class is a JS keyword)
              className="w-16 rounded border border-slate-300 px-2 py-1"
            />
            <Button
              variant="secondary"
              // className = CSS classes (Tailwind) for this element (class is a JS keyword)
              className="px-2 py-1 text-xs"
              // loading="lazy" = load the image only when it gets near the screen
              // { } in JSX = run JavaScript here and show its result
              // isLoading = first load, no data yet
              loading={adjustState.isLoading}
              // disabled = can't be clicked or typed in
              // { } in JSX = run JavaScript here and show its result
              // ! = NOT: flips true/false
              // a || b = OR: a if it is truthy, else b
              // === = strictly equal (same value AND same type)
              disabled={!Number.isInteger(deltaNumber) || deltaNumber === 0}
              // onClick = what happens on click/tap
              // { } in JSX = run JavaScript here and show its result
              // => = an arrow function (a short function)
              onClick={() => applyStock(deltaNumber)}
            >
              {/* { } in JSX = run JavaScript here and show its result
                 a ? b : c = ternary: if a then b else c
                 `text ${x}` = a template string: text with values inserted */}
              {deltaNumber < 0 ? `Remove ${-deltaNumber}` : deltaNumber > 0 ? `Add ${deltaNumber}` : 'Apply'}
            </Button>
          </div>
        </td>
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <td className="px-4 py-3 text-right">
          <button
            // aria-label = the name screen readers read for this element
            // { } in JSX = run JavaScript here and show its result
            // `text ${x}` = a template string: text with values inserted
            aria-label={`Delete variant ${variant.sku}`}
            title="Delete variant"
            // onClick = what happens on click/tap
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onClick={() => {
              // if (...) = run the next part only when the condition is true
              // `text ${x}` = a template string: text with values inserted
              if (confirm(`Delete variant ${variant.sku}?`)) remove({ productId, variantId: variant.id });
            }}
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="rounded p-1.5 text-slate-400 hover:bg-red-50 hover:text-red-600"
          >
            {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
            <Trash2 className="size-4" />
          </button>
        </td>
      </tr>
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {error && (
        <tr>
          {/* { } in JSX = run JavaScript here and show its result
             className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <td colSpan={5} className="px-4 pb-3">
            {/* { } in JSX = run JavaScript here and show its result */}
            <ErrorState message={getErrorMessage(error)} />
          </td>
        </tr>
      )}
    </>
  );
}

// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
function AddVariantRow({ productId }) {
  // const = a name for a value that is never reassigned
  const empty = { sku: '', name: '', price: '', stock: '0' };
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [row, setRow] = useState(empty);
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // { a, b } = destructuring: take properties a and b out of an object
  // isLoading = first load, no data yet
  // useAddVariantMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [add, { isLoading, error }] = useAddVariantMutation();

  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  // async = this function works with await and returns a Promise
  const submit = async () => {
    // const = a name for a value that is never reassigned
    // await = wait for a Promise (async result) before continuing
    const ok = await add({
      productId,
      sku: row.sku,
      name: row.name,
      price: toCents(row.price),
      stock: Number(row.stock),
    })
      // .unwrap() = turn the mutation result into a normal Promise: returns data or throws the error
      .unwrap()
      // => = an arrow function (a short function)
      .then(() => true)
      // => = an arrow function (a short function)
      .catch(() => false);
    // if (...) = run the next part only when the condition is true
    if (ok) setRow(empty);
  };

  // return = give this value back and stop the function here
  return (
    // className = CSS classes (Tailwind) for this element (class is a JS keyword)
    <div className="space-y-2 border-t border-slate-200 bg-slate-50 p-4">
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <p className="text-xs font-semibold uppercase tracking-wide text-slate-500">Add a variant</p>
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="flex flex-wrap gap-2">
        <input
          // placeholder = grey hint text inside an empty input
          placeholder="SKU"
          // { } in JSX = run JavaScript here and show its result
          value={row.sku}
          // onChange = runs on every change of an input
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          // ...x = spread: copy all items/properties of x into here
          onChange={(e) => setRow({ ...row, sku: e.target.value })}
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="w-40 rounded border border-slate-300 px-2 py-1.5 text-sm"
        />
        <input
          // placeholder = grey hint text inside an empty input
          placeholder="Name, e.g. UK 10 / Red"
          // { } in JSX = run JavaScript here and show its result
          value={row.name}
          // onChange = runs on every change of an input
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          // ...x = spread: copy all items/properties of x into here
          onChange={(e) => setRow({ ...row, name: e.target.value })}
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="flex-1 rounded border border-slate-300 px-2 py-1.5 text-sm"
        />
        <input
          // placeholder = grey hint text inside an empty input
          placeholder="Price $"
          type="number"
          min="0.01"
          step="0.01"
          // { } in JSX = run JavaScript here and show its result
          value={row.price}
          // onChange = runs on every change of an input
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          // ...x = spread: copy all items/properties of x into here
          onChange={(e) => setRow({ ...row, price: e.target.value })}
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="w-28 rounded border border-slate-300 px-2 py-1.5 text-sm"
        />
        <input
          // placeholder = grey hint text inside an empty input
          placeholder="Stock"
          type="number"
          min="0"
          step="1"
          // { } in JSX = run JavaScript here and show its result
          value={row.stock}
          // onChange = runs on every change of an input
          // { } in JSX = run JavaScript here and show its result
          // => = an arrow function (a short function)
          // ...x = spread: copy all items/properties of x into here
          onChange={(e) => setRow({ ...row, stock: e.target.value })}
          // className = CSS classes (Tailwind) for this element (class is a JS keyword)
          className="w-20 rounded border border-slate-300 px-2 py-1.5 text-sm"
        />
        {/* loading="lazy" = load the image only when it gets near the screen
           { } in JSX = run JavaScript here and show its result
           isLoading = first load, no data yet
           disabled = can't be clicked or typed in
           ! = NOT: flips true/false
           a || b = OR: a if it is truthy, else b
           onClick = what happens on click/tap */}
        <Button variant="secondary" loading={isLoading} disabled={!row.sku || !row.name || !row.price} onClick={submit}>
          Add
        </Button>
      </div>
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      {row.price && <p className="text-xs text-slate-500">Customers will see {formatPrice(toCents(row.price))}</p>}
      {/* { } in JSX = run JavaScript here and show its result
         a && b = AND; in JSX: show b only when a is true */}
      {error && <ErrorState message={getErrorMessage(error)} />}
    </div>
  );
}
