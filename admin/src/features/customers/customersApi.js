// import = bring in code from another file or package
import { api } from '@/app/api';

// Block, unblock and delete change the list and the dashboard's customer numbers.
// const = a name for a value that is never reassigned
const changed = ['Customer', 'Analytics'];

// export = other files can import this
// const = a name for a value that is never reassigned
// injectEndpoints = add endpoints to the shared API from a feature file
export const customersApi = api.injectEndpoints({
  // endpoints = the list of requests this API can make
  // => = an arrow function (a short function)
  endpoints: (build) => ({
    // build.query = define a READ request: cached, and turned into a useXxxQuery hook
    getCustomers: build.query({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      query: (params) => ({ url: '/admin/customers', params }),
      // providesTags = label this cached data (e.g. Order 5) so it can be refreshed later
      providesTags: ['Customer'],
    }),
    // build.mutation = define a CHANGE request (POST/PATCH/DELETE): turned into a useXxxMutation hook
    blockCustomer: build.mutation({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      // { a, b } = destructuring: take properties a and b out of an object
      // `text ${x}` = a template string: text with values inserted
      query: ({ id, reason }) => ({ url: `/admin/customers/${id}/block`, method: 'POST', body: { reason } }),
      // invalidatesTags = after this change, refetch every query with these labels
      invalidatesTags: changed,
    }),
    // build.mutation = define a CHANGE request (POST/PATCH/DELETE): turned into a useXxxMutation hook
    unblockCustomer: build.mutation({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      // `text ${x}` = a template string: text with values inserted
      query: (id) => ({ url: `/admin/customers/${id}/unblock`, method: 'POST' }),
      // invalidatesTags = after this change, refetch every query with these labels
      invalidatesTags: changed,
    }),
    // Returns { mode: 'deleted' } or { mode: 'anonymised', orderCount }
    // build.mutation = define a CHANGE request (POST/PATCH/DELETE): turned into a useXxxMutation hook
    deleteCustomer: build.mutation({
      // query = build the request (URL, method, body) from the hook's argument
      // => = an arrow function (a short function)
      // `text ${x}` = a template string: text with values inserted
      query: (id) => ({ url: `/admin/customers/${id}`, method: 'DELETE' }),
      // invalidatesTags = after this change, refetch every query with these labels
      // ...x = spread: copy all items/properties of x into here
      invalidatesTags: [...changed, 'Order'], // their orders now show "Deleted customer"
    }),
  }),
});

// export = other files can import this
// const = a name for a value that is never reassigned
// { a, b } = destructuring: take properties a and b out of an object
// useGetCustomersQuery = generated by RTK Query from the endpoint: gives { data, isLoading, isFetching, error } and caches it
// useBlockCustomerMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
// useUnblockCustomerMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
// useDeleteCustomerMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
export const { useGetCustomersQuery, useBlockCustomerMutation, useUnblockCustomerMutation, useDeleteCustomerMutation } =
  customersApi;
