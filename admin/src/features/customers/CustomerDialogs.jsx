// A modal built on the browser's own <dialog>: it traps focus, closes on Escape and dims the
// page by itself, so no dialog library is needed.
// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
// onClose = runs when the dialog closes
// children = whatever is written between this component's opening and closing tags
function Dialog({ title, onClose, children }) {
  // const = a name for a value that is never reassigned
  // useRef = a box (.current) that keeps a value or a DOM element without causing a redraw
  const ref = useRef(null);
  // useEffect = run code AFTER the screen is drawn (timers, events, browser APIs); re-runs when its [deps] change
  // => = an arrow function (a short function)
  useEffect(() => {
    // ?.() = call only if the function exists
    // ?. = optional chaining: stop (undefined) instead of crashing if the left side is null/undefined
    // showModal = open a <dialog> as a modal (dims the page, traps focus)
    ref.current?.showModal();
  }, []);
  // return = give this value back and stop the function here
  return (
    // <dialog> = the browser's built-in popup (focus trap, Esc to close)
    <dialog
      // ref = after drawing, put this element into a useRef box (.current)
      // { } in JSX = run JavaScript here and show its result
      ref={ref}
      // onClose = runs when the dialog closes
      // { } in JSX = run JavaScript here and show its result
      onClose={onClose}
      // className = CSS classes (Tailwind) for this element (class is a JS keyword)
      className="m-auto w-full max-w-md rounded-xl p-0 shadow-xl backdrop:bg-slate-900/40"
      // aria-labelledby = the element (by id) that names this one
      aria-labelledby="dialog-title"
    >
      {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <div className="space-y-4 p-6">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <h2 id="dialog-title" className="text-lg font-semibold">
          {/* { } in JSX = run JavaScript here and show its result */}
          {title}
        </h2>
        {/* { } in JSX = run JavaScript here and show its result
           children = whatever is written between this component's opening and closing tags */}
        {children}
      </div>
    </dialog>
  );
}

// export = other files can import this
// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
// onClose = runs when the dialog closes
export function BlockDialog({ customer, onClose, onDone }) {
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [reason, setReason] = useState('');
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // { a, b } = destructuring: take properties a and b out of an object
  // isLoading = first load, no data yet
  // useBlockCustomerMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [block, { isLoading, error }] = useBlockCustomerMutation();

  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  // async = this function works with await and returns a Promise
  const submit = async (e) => {
    // preventDefault = stop the browser's default action (form submit reload, link follow)
    e.preventDefault();
    // try / catch = if the code inside fails, run the catch part instead of crashing
    try {
      // await = wait for a Promise (async result) before continuing
      // .trim = remove spaces at both ends
      // a || b = OR: a if it is truthy, else b
      // .unwrap() = turn the mutation result into a normal Promise: returns data or throws the error
      await block({ id: customer.id, reason: reason.trim() || undefined }).unwrap();
      onDone();
    } catch {
      // shown below
    }
  };

  // return = give this value back and stop the function here
  return (
    // { } in JSX = run JavaScript here and show its result
    // `text ${x}` = a template string: text with values inserted
    // onClose = runs when the dialog closes
    <Dialog title={`Block ${customer.name}?`} onClose={onClose}>
      {/* <form> = groups inputs; Enter or a submit button sends it (onSubmit)
         onSubmit = runs when the form is sent (Enter or submit button)
         { } in JSX = run JavaScript here and show its result
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <form onSubmit={submit} className="space-y-4">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <ul className="list-disc space-y-1 pl-5 text-sm text-slate-600">
          <li>They can&apos;t log in, place orders or reset their password.</li>
          <li>They&apos;re logged out everywhere within 15 minutes.</li>
          <li>Their orders and data stay. You can unblock them at any time.</li>
        </ul>
        {/* <label> = the name of an input; clicking it focuses the input
           className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <label className="block">
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <span className="mb-1.5 block text-sm font-medium text-slate-700">Reason (only admins see this)</span>
          <input
            // { } in JSX = run JavaScript here and show its result
            value={reason}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setReason(e.target.value)}
            // maxLength = maximum number of characters
            // { } in JSX = run JavaScript here and show its result
            maxLength={200}
            // placeholder = grey hint text inside an empty input
            placeholder="e.g. repeated chargebacks"
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="w-full rounded-lg border border-slate-300 px-3 py-2 text-sm outline-none focus:border-brand-500"
          />
        </label>
        {/* { } in JSX = run JavaScript here and show its result
           a && b = AND; in JSX: show b only when a is true */}
        {error && <ErrorState message={getErrorMessage(error)} />}
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <div className="flex justify-end gap-2">
          {/* onClick = what happens on click/tap
             { } in JSX = run JavaScript here and show its result
             onClose = runs when the dialog closes */}
          <Button type="button" variant="secondary" onClick={onClose}>
            Cancel
          </Button>
          {/* loading="lazy" = load the image only when it gets near the screen
             { } in JSX = run JavaScript here and show its result
             isLoading = first load, no data yet */}
          <Button type="submit" variant="danger" loading={isLoading}>
            Block customer
          </Button>
        </div>
      </form>
    </Dialog>
  );
}

// Deleting can't be undone, so the admin types the customer's email to confirm
// (the same idea as GitHub's "type the repository name to delete it").
// export = other files can import this
// function Name() = a React component (capital letter): returns what to show (JSX)
// { a, b } = destructuring: take properties a and b out of an object
// onClose = runs when the dialog closes
export function DeleteDialog({ customer, onClose, onDone }) {
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // useState = a value the component remembers; calling its setter redraws the component
  const [typed, setTyped] = useState('');
  // const = a name for a value that is never reassigned
  // [a, b] = destructuring: take the first and second items of an array
  // { a, b } = destructuring: take properties a and b out of an object
  // isLoading = first load, no data yet
  // useDeleteCustomerMutation = generated by RTK Query: gives [trigger, { isLoading }]; calling trigger sends the change
  const [remove, { isLoading, error }] = useDeleteCustomerMutation();
  // const = a name for a value that is never reassigned
  // .trim = remove spaces at both ends
  // === = strictly equal (same value AND same type)
  const confirmed = typed.trim().toLowerCase() === customer.email.toLowerCase();

  // const = a name for a value that is never reassigned
  // => = an arrow function (a short function)
  // async = this function works with await and returns a Promise
  const submit = async (e) => {
    // preventDefault = stop the browser's default action (form submit reload, link follow)
    e.preventDefault();
    // if (...) = run the next part only when the condition is true
    // ! = NOT: flips true/false
    // return = give this value back and stop the function here
    if (!confirmed) return;
    // try / catch = if the code inside fails, run the catch part instead of crashing
    try {
      // await = wait for a Promise (async result) before continuing
      // .unwrap() = turn the mutation result into a normal Promise: returns data or throws the error
      onDone(await remove(customer.id).unwrap());
    } catch {
      // shown below
    }
  };

  // return = give this value back and stop the function here
  return (
    // { } in JSX = run JavaScript here and show its result
    // `text ${x}` = a template string: text with values inserted
    // onClose = runs when the dialog closes
    <Dialog title={`Delete ${customer.name}?`} onClose={onClose}>
      {/* <form> = groups inputs; Enter or a submit button sends it (onSubmit)
         onSubmit = runs when the form is sent (Enter or submit button)
         { } in JSX = run JavaScript here and show its result
         className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
      <form onSubmit={submit} className="space-y-4">
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <p className="text-sm text-slate-600">
          {/* { } in JSX = run JavaScript here and show its result
             a ? b : c = ternary: if a then b else c
             === = strictly equal (same value AND same type) */}
          {customer.orderCount === 0
            ? 'This customer has no orders, so the account is deleted completely.'
            // `text ${x}` = a template string: text with values inserted
            // { } in JSX = run JavaScript here and show its result
            : `This customer has ${customer.orderCount} order(s). Those must be kept for the accounts, so their name, email, phone, addresses, cart and wishlist are erased and the orders show "Deleted customer".`}{' '}
          <strong>This cannot be undone.</strong>
        </p>
        {/* <label> = the name of an input; clicking it focuses the input
           className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <label className="block">
          {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
          <span className="mb-1.5 block text-sm font-medium text-slate-700">
            Type <span className="font-mono">{customer.email}</span> to confirm
          </span>
          <input
            // { } in JSX = run JavaScript here and show its result
            value={typed}
            // onChange = runs on every change of an input
            // { } in JSX = run JavaScript here and show its result
            // => = an arrow function (a short function)
            onChange={(e) => setTyped(e.target.value)}
            // autoComplete = tells the browser what to auto-fill (email, password, address...)
            autoComplete="off"
            // className = CSS classes (Tailwind) for this element (class is a JS keyword)
            className="w-full rounded-lg border border-slate-300 px-3 py-2 text-sm outline-none focus:border-red-500"
          />
        </label>
        {/* { } in JSX = run JavaScript here and show its result
           a && b = AND; in JSX: show b only when a is true */}
        {error && <ErrorState message={getErrorMessage(error)} />}
        {/* className = CSS classes (Tailwind) for this element (class is a JS keyword) */}
        <div className="flex justify-end gap-2">
          {/* onClick = what happens on click/tap
             { } in JSX = run JavaScript here and show its result
             onClose = runs when the dialog closes */}
          <Button type="button" variant="secondary" onClick={onClose}>
            Cancel
          </Button>
          {/* loading="lazy" = load the image only when it gets near the screen
             { } in JSX = run JavaScript here and show its result
             isLoading = first load, no data yet
             disabled = can't be clicked or typed in
             ! = NOT: flips true/false */}
          <Button type="submit" variant="danger" loading={isLoading} disabled={!confirmed}>
            Delete customer
          </Button>
        </div>
      </form>
    </Dialog>
  );
}
